import { AppBrief } from './types';

/**
 * Formats a comprehensive, professional Markdown technical blueprint for Every Nation GG.
 */
export function generateBlueprintMarkdown(
  brief: Partial<AppBrief>,
  clientName: string,
  company?: string,
  token?: string
): string {
  const dateStr = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });

  const lines = [
    `# ${brief.project_title || 'Application Technical Blueprint'}`,
    `*Prepared by VISIEN for Every Nation GG • ${dateStr}*\n`,
    `---`,
    `\n## 1. Executive Summary`,
    `- **Client:** ${clientName}${company ? ` (${company})` : ''}`,
    token ? `- **Session Token:** \`${token}\`` : '',
    `- **Vision:** ${brief.vision_summary || 'N/A'}`,
    `- **Problem Solved:** ${brief.problem_statement || 'N/A'}`,
    brief.current_workflow ? `- **Current Workflow:** ${brief.current_workflow}` : '',
    `\n---`,
    `\n## 2. Target Users & User Flow`,
    `- **Target Users:** ${brief.target_users || 'N/A'}`,
    brief.user_roles ? `- **User Roles & Access:** ${brief.user_roles}` : '',
    `- **First Screen Experience:** ${brief.first_screen_experience || 'N/A'}`,
    `- **Core Action / Flow:** ${brief.core_action || 'N/A'}`,
    `- **Expected Outcome:** ${brief.expected_outcome || 'N/A'}`,
    `\n---`,
    `\n## 3. Technical Specifications & Integrations`,
    `- **Target Platform:** ${brief.target_platform || 'iOS / Android & Modern Web'}`,
    `- **Auth & Security:** ${brief.auth_requirements || 'Standard secure authentication'}`,
    `- **Payments & Integrations:** ${brief.payments_integrations || 'Not specified'}`,
    `- **Notifications & Channels:** ${brief.notifications_channels || 'Push notifications / Email'}`,
    `- **Hardware & Capabilities:** ${brief.hardware_capabilities || 'Standard mobile & web'}`,
    `- **Data Readiness:** ${brief.data_readiness || 'Ready for ingestion'}`,
    `- **Infrastructure Preference:** ${brief.infrastructure_preference || 'ENGG Cloud Managed'}`,
    `\n---`,
    `\n## 4. V1 Essential Feature Scope`,
    brief.v1_essential_features && brief.v1_essential_features.length > 0
      ? brief.v1_essential_features.map((f) => `- [ ] **${f}**`).join('\n')
      : '- [ ] Core MVP features',
    brief.future_horizon ? `\n### Future Horizon\n${brief.future_horizon}` : '',
    `\n---`,
    `\n## 5. Visual Direction & Aesthetics`,
    `- **Visual Direction:** ${brief.visual_direction || 'Modern, clean, intuitive'}`,
    brief.emotional_ux_feel && brief.emotional_ux_feel.length > 0
      ? `- **Vibe Tags:** ${brief.emotional_ux_feel.join(', ')}`
      : '',
    brief.anti_patterns && brief.anti_patterns.length > 0
      ? `- **Do NOT Want (Anti-patterns):** ${brief.anti_patterns.join(', ')}`
      : '',
    `\n---`,
    `\n## 6. Target Launch & Budget Scope`,
    brief.target_timeline ? `- **Target Timeline:** ${brief.target_timeline}` : '',
    brief.budget_range ? `- **Budget Range:** ${brief.budget_range}` : '',
    `\n---`,
    `\n*Generated by VISIEN — Vision Inspired by Story and Idea*`,
    `*Every Nation GG • Software Design & Engineering Studio*`,
  ];

  return lines.filter(Boolean).join('\n');
}

/**
 * Triggers a browser download of the formatted technical blueprint Markdown file.
 */
export function downloadBlueprintMarkdown(
  brief: Partial<AppBrief>,
  clientName: string,
  company?: string,
  token?: string
) {
  const content = generateBlueprintMarkdown(brief, clientName, company, token);
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  const filename = `${(brief.project_title || 'visien-blueprint')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')}.md`;
  anchor.href = url;
  anchor.download = filename;
  anchor.click();
  URL.revokeObjectURL(url);
}

